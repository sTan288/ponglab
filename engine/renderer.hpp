//renderer.hpp
#pragma once
#include <SFML/Graphics.hpp>

// Renderer — система отрисовки.
// Главная идея: в render() сущности и сцены НЕ рисуют сразу, а только кладут то, что
// нужно нарисовать (sf::Drawable: фигуры, спрайты, текст), в ОЧЕРЕДЬ через queue().
// В конце кадра Renderer::render() рисует всю очередь разом и очищает её.
//
// Зачем так:
//  - окно не нужно передавать по всему коду: Renderer помнит его сам;
//  - легко посчитать, сколько всего рисуется за кадр;
//  - можно оптимизировать: отсортировать очередь (фон первым), выкинуть что-то из отрисовки и т.д.
//
// namespace, а не класс: это просто набор функций, объединённых одним именем Renderer::...
// (объект создавать не нужно, как и у статического класса).
namespace Renderer {
    void initialise(sf::RenderWindow &);  //запомнить окно, в котором рисовать (вызывается один раз)
    sf::RenderWindow &get_window();       //получить это окно из любого места кода

    void shutdown();                      //очистить очередь (при выходе из игры)
    void update(const float &);           //обновление за кадр (пока ничего не делает)
    void queue(const sf::Drawable *s);    //добавить объект в очередь на отрисовку
    void render();                        //нарисовать всю очередь и очистить её
};
